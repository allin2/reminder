#!/usr/bin/env node
/**
 * 按 `@capacitor/cli` 的 `updateAndroid()` 复刻本仓的
 * `android/capacitor-cordova-android-plugins/`（gitignored，跑 `cap sync` 会先删后重建）。
 *
 * 为什么需要它：`cap sync android` 在沙箱批量删除护栏下**只跑成功了一半** ——
 * 它把该目录删空、但没重建出来，于是 Gradle 报
 * `Could not read script '.../cordova.variables.gradle' as it does not exist`。
 * 该目录被 `android/.gitignore` 忽略 ⇒ `git` 恢复不了；护栏按「回合」计数（TTL 7 天）
 * ⇒ 同一回合内重跑 `cap sync` 必然再次被拦。
 *
 * 做法：**只写文件、不删除**，内容逐条复刻 CLI 对本仓（**0 个 cordova 插件**）会生成的产物：
 *   · 模板 `node_modules/@capacitor/cli/assets/capacitor-cordova-android-plugins.tar.gz`
 *   · `handleCordovaPluginsGradle()`：SUB-PROJECT DEPENDENCIES / PLUGIN GRADLE EXTENSIONS 两段替换
 *     （cordovaPlugins=[] ⇒ frameworkString 为空、applyString 只有 variables 那一行；kotlinNeeded=false）
 *   · 同函数写出的 `cordova.variables.gradle`（`config.android.minVersion` 默认 '22'）
 *
 * 这不是「构建脚本的替代品」—— 它只补回被删掉的那个生成目录，
 * 真正的产物仍然由 `./gradlew assembleDebug assembleRelease` 产出，
 * 并由 `apk-web-assets.sh` 逐字节核对包内 Web 资源、再由「与上轮候选逐条目比对」核对等价性。
 *
 * 用法：node restore-cordova-plugins-project.js
 */
const fs = require("fs");
const path = require("path");
const { execFileSync } = require("child_process");

const ROOT = path.resolve(__dirname, "../../../..");
const DIR = path.join(ROOT, "android/capacitor-cordova-android-plugins");
const TEMPLATE = path.join(ROOT, "node_modules/@capacitor/cli/assets/capacitor-cordova-android-plugins.tar.gz");
const MIN_SDK = 22;   // @capacitor/cli dist/config.js:199  android.minVersion 默认值

fs.mkdirSync(DIR, { recursive: true });

// 1) 模板（只解压覆盖，不删任何东西）
execFileSync("tar", ["-xzf", TEMPLATE, "-C", DIR]);

// 2) handleCordovaPluginsGradle：0 个 cordova 插件时的两次替换
const gradlePath = path.join(DIR, "build.gradle");
let buildGradle = fs.readFileSync(gradlePath, "utf8");
const frameworks = "";                                   // 无 framework ⇒ frameworkString 为空
const applies = 'apply from: "cordova.variables.gradle"'; // applyArray 只有这一条
buildGradle = buildGradle.replace(
  /(SUB-PROJECT DEPENDENCIES START)[\s\S]*(\/\/ SUB-PROJECT DEPENDENCIES END)/,
  "$1\n" + frameworks + "\n    $2"
);
buildGradle = buildGradle.replace(
  /(PLUGIN GRADLE EXTENSIONS START)[\s\S]*(\/\/ PLUGIN GRADLE EXTENSIONS END)/,
  "$1\n" + applies + "\n$2"
);
fs.writeFileSync(gradlePath, buildGradle);

// 3) 同函数写出的 cordova.variables.gradle
fs.writeFileSync(path.join(DIR, "cordova.variables.gradle"),
`// DO NOT EDIT THIS FILE! IT IS GENERATED EACH TIME "capacitor update" IS RUN
ext {
  cdvMinSdkVersion = project.hasProperty('minSdkVersion') ? rootProject.ext.minSdkVersion : ${MIN_SDK}
  // Plugin gradle extensions can append to this to have code run at the end.
  cdvPluginPostBuildExtras = []
  cordovaConfig = [:]
}
`);

// 4) 0 个插件 ⇒ manifest 就是模板本身（rootXMLEntries / applicationXMLEntries 都为空）
console.log("restored (write-only):");
["build.gradle", "cordova.variables.gradle", "src/main/AndroidManifest.xml"].forEach(f => {
  console.log("  " + path.join(DIR, f) + "  " + fs.statSync(path.join(DIR, f)).size + " bytes");
});
